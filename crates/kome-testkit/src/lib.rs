//! kome の決定的シミュレーション用の試験基盤。
//!
//! [`drive`] はバイト列を操作列として解釈し、一つの [`kome::Kernel`] に適用する。
//! 時刻・I/O の完了・実行するスレッドは、すべてバイト列が決める。同じバイト列からは
//! 同じ状態と同じ `Effect` 列を得る。property test (`tests/sim.rs`) と fuzz
//! (`fuzz/fuzz_targets/drive.rs`) は同じ `drive` を使う。fuzz が見つけた入力は
//! `tests/regressions/` へ置くと、通常の試験が毎回再生する。
//!
//! 操作のたびに次を確かめる。
//!
//! - [`kome::Kernel::audit`] が通る (一つの状態で判定できる不変条件)。
//! - 失敗した操作は状態を変えていない。内部の障害 (`Error::Broken`) は起きない。
//! - 履歴の監視 ([`sim`]): 終端は一度だけ、待機の結果は一つだけ、実行権は一つだけ、
//!   回収した ID は再び現れない、使用中の実体は解放しない、権限を減らした後は古い実行が
//!   止まるまで貸さない、消費する資源の数は増減の合計と一致する。
//! - 独立したモデル ([`pages`]) とメモリの見え方が一致する。
//! - 独立したモデル ([`pipes`]) と通信路の中身、読める・書けるの通知が一致する。
//! - 通知だけから組み立てたアドレス空間 ([`shadow`]) がモデルと一致し、ゲストのアドレスでの
//!   読み書きの結果がモデルと一致する。
//!
//! [`host`] は、I/O の内容とメモリの内容を持つ制御可能なホストである。

pub mod host;
pub mod pages;
pub mod pipes;
pub mod shadow;
pub mod sim;

pub use sim::{Failure, Probe, Summary, drive, drive_probed};
